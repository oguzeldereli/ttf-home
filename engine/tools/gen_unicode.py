"""Generate src/ttf_unicode.inc: the Unicode data the tokenizer needs (from Python's unicodedata).

  - class ranges: L (letters), M (marks), N (numbers), and White_Space, for the GPT-4-style pre-tokenizer regexes;
  - NFC: canonical combining classes, full canonical decompositions, and the primary composites (pairs that NFC
    composes, i.e. canonical pairs minus the composition exclusions).

    python tools/gen_unicode.py > src/ttf_unicode.inc
"""
import sys
import unicodedata as ud

MAXCP = 0x110000
# White_Space (PropList.txt); \s in the HF tokenizers' regex engine (Oniguruma, UTF-8) is this property
WHITE_SPACE = [*range(0x09, 0x0E), 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B), 0x2028, 0x2029, 0x202F, 0x205F,
               0x3000]


def flags(cp):
    c = ud.category(chr(cp))
    f = 0
    if c[0] == "L":
        f |= 1
    if c[0] == "M":
        f |= 2
    if c[0] == "N":
        f |= 4
    return f


def ranges(fn):
    out, start, cur = [], 0, fn(0)
    for cp in range(1, MAXCP):
        v = fn(cp)
        if v != cur:
            if cur:
                out.append((start, cp - 1, cur))
            start, cur = cp, v
    if cur:
        out.append((start, MAXCP - 1, cur))
    return out


def full_decomp(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return [cp]
    return [x for h in d.split() for x in full_decomp(int(h, 16))]


def main():
    w = sys.stdout.write
    w("// generated by tools/gen_unicode.py from Python unicodedata %s; do not edit\n" % ud.unidata_version)
    cls = ranges(flags)
    ws = set(WHITE_SPACE)
    w("static const uint32_t k_uclass[][3] = {  // first, last, flags (1 L, 2 M, 4 N)\n")
    for a, b, f in cls:
        w("    { 0x%X, 0x%X, %d },\n" % (a, b, f))
    w("};\n")
    w("static const uint32_t k_uspace[] = { %s };\n" % ", ".join("0x%X" % c for c in sorted(ws)))
    ccc = ranges(lambda cp: ud.combining(chr(cp)))
    w("static const uint32_t k_uccc[][3] = {  // first, last, canonical combining class\n")
    for a, b, f in ccc:
        w("    { 0x%X, 0x%X, %d },\n" % (a, b, f))
    w("};\n")
    w("static const uint32_t k_udecomp[][5] = {  // cp, its full canonical decomposition (0-padded); Hangul excluded\n")
    nd = 0
    for cp in range(MAXCP):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = full_decomp(cp)
        if d != [cp]:
            assert len(d) <= 4, hex(cp)
            assert ud.normalize("NFD", chr(cp)) == "".join(map(chr, d)), hex(cp)
            w("    { 0x%X, %s },\n" % (cp, ", ".join("0x%X" % x for x in d + [0] * (4 - len(d)))))
            nd += 1
    w("};\n")
    w("static const uint32_t k_ucomp[][3] = {  // starter, combining, composite (primary composites)\n")
    pairs = []
    for cp in range(MAXCP):
        if 0xAC00 <= cp <= 0xD7A3:
            continue
        d = ud.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        p = [int(h, 16) for h in d.split()]
        if len(p) == 2 and ud.normalize("NFC", chr(p[0]) + chr(p[1])) == chr(cp):
            pairs.append((p[0], p[1], cp))
    for a, b, c in sorted(pairs):
        w("    { 0x%X, 0x%X, 0x%X },\n" % (a, b, c))
    w("};\n")
    # the tokenizer skips NFC for text below U+0300: check that this is exact
    for cp in range(0x300):
        assert ud.normalize("NFC", chr(cp)) == chr(cp)
    print("classes %d, ccc %d, decomp %d, comp %d" % (len(cls), len(ccc), nd, len(pairs)), file=sys.stderr)


if __name__ == "__main__":
    main()
